#!/usr/bin/env node
// Builds timelock-selectors.js: function selector -> name and inputs for every
// state-changing function the USD8 timelock can call, taken from usd8-core's
// compiled Foundry artifacts. The docs page uses it to describe queued calls.
//
//   node scripts/build-timelock-selectors.mjs [path/to/usd8core]
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';

const core = resolve(process.argv[2] || '../usd8core');
const CONTRACTS = [
  'Registry', 'Treasury', 'DefiInsurance', 'SingleAssetCoverPool', 'USD8', 'USD8PriceOracle',
  'USD8SavingsAdapter', 'TimelockController', 'UpgradeableBeacon', 'ERC4626Strategy',
  'AaveV3USDCStrategy', 'MorphoPTReUSDDec2026Strategy',
];

function canonical(param) {
  if (!param.type.startsWith('tuple')) return param.type;
  return `(${param.components.map(canonical).join(',')})${param.type.slice('tuple'.length)}`;
}

function strip(param) {
  const out = { name: param.name, type: param.type };
  if (param.components) out.components = param.components.map(strip);
  return out;
}

const selectors = {};
for (const name of CONTRACTS) {
  const file = resolve(core, 'out', `${name}.sol`, `${name}.json`);
  if (!existsSync(file)) throw new Error(`Missing artifact ${file}; run forge build in usd8-core`);
  const artifact = JSON.parse(readFileSync(file, 'utf8'));
  for (const entry of artifact.abi) {
    if (entry.type !== 'function' || entry.stateMutability === 'view' || entry.stateMutability === 'pure') continue;
    const signature = `${entry.name}(${entry.inputs.map(canonical).join(',')})`;
    const selector = artifact.methodIdentifiers[signature];
    if (!selector) throw new Error(`No selector for ${name}.${signature}`);
    const key = `0x${selector}`;
    // Same signature in several contracts (e.g. initialize) keeps the first one's parameter names.
    if (selectors[key]) {
      if (selectors[key].signature !== signature) throw new Error(`Selector clash ${key}: ${selectors[key].signature} vs ${signature}`);
      continue;
    }
    selectors[key] = { signature, name: entry.name, inputs: entry.inputs.map(strip) };
  }
}

const sorted = Object.fromEntries(Object.entries(selectors)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([key, { signature, ...rest }]) => [key, rest]));
writeFileSync(
  resolve('timelock-selectors.js'),
  `// Generated by scripts/build-timelock-selectors.mjs from usd8-core artifacts. Do not edit.\n`
    + `window.USD8_TIMELOCK_SELECTORS = ${JSON.stringify(sorted, null, 1)};\n`,
);
console.log(`timelock-selectors.js: ${Object.keys(sorted).length} functions from ${CONTRACTS.length} contracts`);
